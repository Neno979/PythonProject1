print("welcome to mood checker")
mood = input("What is your current mood?")

if mood == "happy":
    print("Great to see you happy")
elif mood == "nervous":
    print("Take a deep breath 3 times.")
elif mood == "sad":
    print("seeing you sad makes me sad")
elif mood == "excited":
    print("wow! you are excited")
elif mood == "relaxed":
    print("you are relaxed")
else:
    print("i dont recognise this mood")